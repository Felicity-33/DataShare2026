// ============================================================
// 裁决说明书存档（localStorage，按 escrowId 落盘）
// ------------------------------------------------------------
// 监管每次实际发起裁决交易前，都会把「裁决说明书」存档到本地，
// 供后续审计报告导出并档。存档结构与界面展示的四要素一致。
// ============================================================
const RULING_DOC_KEY = 'dv_ruling_docs_v1';

// 读取全部已存档的裁决说明书：{ [escrowId]: doc }
export function getRulingDocs() {
  try {
    return JSON.parse(localStorage.getItem(RULING_DOC_KEY) || '{}');
  } catch {
    return {};
  }
}

// 读取单笔托管单的裁决说明书（无存档返回 null）
export function getRulingDoc(escrowId) {
  return getRulingDocs()[escrowId] || null;
}

// 存档 / 覆盖一份裁决说明书
export function saveRulingDoc(escrowId, doc) {
  try {
    const all = getRulingDocs();
    all[escrowId] = { ...doc, archivedAt: Date.now() };
    localStorage.setItem(RULING_DOC_KEY, JSON.stringify(all));
  } catch { /* 存储不可用时静默降级：不影响裁决交易本身 */ }
}
